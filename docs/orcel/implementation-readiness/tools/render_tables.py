"""Render DONOR_REGISTRY.md, SOURCE_TRANSPLANT_MATRIX.md and IMPLEMENTATION_BACKLOG.md
from the JSON sources so the tables never drift from the data.

Usage: python -I docs/orcel/implementation-readiness/tools/render_tables.py [--check]
--check exits 1 when a rendered file differs from what is on disk.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

PKG = Path(__file__).resolve().parent.parent
HEADER = "<!-- Generated by tools/render_tables.py from {src}. Edit the JSON, then re-render. -->\n\n"


def cell(value) -> str:
    text = value if isinstance(value, str) else json.dumps(value, ensure_ascii=False)
    return text.replace("|", "\\|").replace("\n", " ")


def donors_md(reg: dict) -> str:
    out = [HEADER.format(src="donor_registry.json"), "# Authorized donor registry\n\n"]
    out.append(
        f"Status: {reg['status']}. Verified {reg['verified_on']} against Orcel main "
        f"`{reg['orcel_base'][:12]}`. {reg['verified_by']}.\n\n"
        "Authorization records: " + "; ".join(f"`{a}`" if a.startswith("docs/") else a for a in reg["authorization_records"]) + ".\n\n"
        "A founder authorization reaches only code its grantor owns. Third-party files inside a donor, every dependency, "
        "model weights, datasets, trademarks and hosted services keep their own terms. Every import still needs its "
        "provenance record, notice and the import gate of `docs/canonical/ORCEL_P20_DONOR_LEDGER.md`.\n\n"
    )
    out.append("| Donor | Tier | Pin | Root license | Strategy | Status | Blueprint |\n|---|---:|---|---|---|---|---|\n")
    for d in reg["donors"]:
        pin = f"[`{d['commit'][:12]}`](https://github.com/{d['repo']}/tree/{d['commit']})"
        out.append(
            f"| [{d['repo']}](https://github.com/{d['repo']}) | {d['tier']} | {pin} | {cell(d['root_license'])} | "
            f"{d['strategy']} | {d['status']} | [{d['blueprint']}]({d['blueprint']}) |\n"
        )
    out.append("\n## Decisions and limits per donor\n\n")
    for d in reg["donors"]:
        out.append(f"### {d['repo']}\n\n")
        out.append(f"- Pin: `{d['commit']}` ({d['commit_date']})")
        if d.get("latest_inspected"):
            out.append(f"; newest inspected head `{d['latest_inspected']}`")
        if d.get("previous_pins"):
            out.append("; earlier Orcel pins " + ", ".join(f"`{p[:12]}`" for p in d["previous_pins"]))
        out.append("\n")
        out.append(f"- Source access: {d['source_access']}\n")
        out.append(f"- License evidence: {d['license_evidence']}\n")
        for comp, lic in d.get("component_licenses", {}).items():
            out.append(f"- Component license: `{comp}`: {lic}\n")
        out.append(f"- Strategy ({d['strategy']}): {d['strategy_detail']}\n\n")
    out.append("## Sources named but not inventoried\n\n")
    for u in reg["unresolved_sources"]:
        out.append(f"- **{u['name']}.** {u['reason']}\n")
    return "".join(out)


def matrix_md(matrix: dict, reg: dict) -> str:
    pins = {d["id"]: d for d in reg["donors"]}
    out = [HEADER.format(src="transplant_matrix.json"), "# Source transplant matrix\n\n"]
    out.append(
        "Status: " + matrix["status"] + ". " + matrix["note"] + "\n\n"
        "| Row | Donor @ pin | Source | Object | Method | Orcel destination | Task | Notes |\n|---|---|---|---|---|---|---|---|\n"
    )
    for r in matrix["rows"]:
        d = pins[r["donor"]]
        at = r.get("at", d["commit"])
        obj = f"`{r['object'][:12]}`" if r.get("object") else "-"
        out.append(
            f"| {r['id']} | {d['repo']} @ `{at[:12]}` | `{r['path']}` | {obj} | {r['method']} | "
            f"`{r['dest']}` ({r['dest_state']}) | {r['task']} | {cell(r['notes'])} |\n"
        )
    return "".join(out)


def backlog_md(backlog: dict) -> str:
    out = [HEADER.format(src="backlog/tasks.json"), "# Implementation backlog\n\n"]
    out.append(
        f"Status: {backlog['status']}\n\nEstimates: {backlog['estimate_scale']}\n\n"
        "Gates every task inherits:\n\n" + "".join(f"- {g}\n" for g in backlog["common_gates"]) + "\n"
    )
    out.append("## Summary\n\n| Task | Phase | Status | Method | Title | Depends on | Estimate (days) | Grain |\n|---|---|---|---|---|---|---|---|\n")
    for t in backlog["tasks"]:
        out.append(
            f"| [{t['id']}](#{t['id'].lower()}) | {t['phase']} | {t['status']} | {t['method']} | {cell(t['title'])} | "
            f"{', '.join(t['depends_on']) or '-'} | {t['estimate']} | {t['proposed_grain']} |\n"
        )
    out.append("\n## Founder decisions\n\n| Id | Status | Question | Blocks | If no answer |\n|---|---|---|---|---|\n")
    for f in backlog["founder_decisions"]:
        out.append(f"| {f['id']} | {cell(f.get('status', 'OPEN'))} | {cell(f['question'])} | {cell(', '.join(f['blocks']))} | {cell(f['default_if_silent'])} |\n")
    out.append("\n## External dependencies\n\n")
    for e in backlog["external_dependencies"]:
        out.append(f"- **{e['id']}**: {e['meaning']}\n")
    out.append("\n## Task cards\n")
    for t in backlog["tasks"]:
        out.append(f"\n### {t['id']}\n\n**{t['title']}** · phase {t['phase']} · {t['status']} · estimate {t['estimate']} days (ESTIMATE) · proposed grain {t['proposed_grain']}\n\n")
        out.append(f"- **Objective.** {t['objective']}\n- **User-visible capability.** {t['user_visible']}\n")
        out.append("- **Existing Orcel implementation.** " + ("; ".join(f"`{x}`" for x in t["existing_orcel"]) or "none") + "\n")
        out.append(f"- **Donor.** {t['donor'] or 'none'} · method {t['method']}\n")
        if t["donor_files"]:
            out.append("- **Donor files.** " + "; ".join(f"`{x}`" for x in t["donor_files"]) + "\n")
        cr = t["orcel_files"].get("create", [])
        ch = t["orcel_files"].get("change", [])
        out.append("- **Create.** " + ("; ".join(f"`{x}`" for x in cr) or "none") + "\n")
        out.append("- **Change.** " + ("; ".join(f"`{x}`" for x in ch) or "none") + "\n")
        out.append(f"- **Dependencies to admit.** {t['dependencies']}\n- **Interface.** {t['interfaces']}\n")
        out.append("- **Platforms.** " + "; ".join(f"{k}: {v}" for k, v in t["platforms"].items()) + "\n")
        out.append(f"- **Security and authority.** {t['security']} Authority delta: {t['authority_delta'].rstrip('.')}.\n")
        out.append("- **Steps.**\n" + "".join(f"  {i}. {s}\n" for i, s in enumerate(t["steps"], 1)))
        out.append("- **Tests.**\n")
        for k in ("positive", "negative", "recovery", "e2e"):
            items = t["tests"].get(k, [])
            out.append(f"  - {k}: " + ("; ".join(items) if items else "none required") + "\n")
        out.append(f"- **Performance.** {t['performance']}\n- **CI.** {t['ci']}\n")
        out.append("- **Depends on.** " + (", ".join(t["depends_on"]) or "nothing") + "\n")
        out.append("- **Acceptance.**\n" + "".join(f"  - {a}\n" for a in t["acceptance"]))
        out.append(f"- **Definition of done.** {t['done']}\n- **Rollback.** {t['rollback']}\n")
        r = t.get("reuse")
        if r:
            out.append(
                f"- **Reuse review (2026-10-18).** {r['before']} → {r['after']}; ESTIMATE {r['estimate_build_new_days']} days if built new, "
                f"{r['estimate_with_reuse_days']} with reuse. Runtime overhead: {r['runtime_overhead']}. Maintenance: {r['maintenance']}."
                + (f" Matrix rows: {', '.join(r['matrix_rows'])}." if r["matrix_rows"] else "")
                + (f" Risks: {'; '.join(r['risks'])}." if r["risks"] else "")
                + "\n"
            )
            if r.get("build_new_justification"):
                out.append(f"- **Why not reuse.** {r['build_new_justification']}\n")
    return "".join(out)


def main() -> int:
    check = "--check" in sys.argv
    reg = json.loads((PKG / "donor_registry.json").read_text(encoding="utf-8"))
    matrix = json.loads((PKG / "transplant_matrix.json").read_text(encoding="utf-8"))
    backlog = json.loads((PKG / "backlog/tasks.json").read_text(encoding="utf-8"))
    outputs = {
        "DONOR_REGISTRY.md": donors_md(reg),
        "SOURCE_TRANSPLANT_MATRIX.md": matrix_md(matrix, reg),
        "IMPLEMENTATION_BACKLOG.md": backlog_md(backlog),
    }
    stale = []
    for name, text in outputs.items():
        path = PKG / name
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
    if stale:
        print("stale rendered files: " + ", ".join(stale))
        return 1
    print("rendered tables " + ("up to date" if check else "written"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
