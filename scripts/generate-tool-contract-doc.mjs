#!/usr/bin/env node
// Generates docs/p16/TOOL_CONTRACT.md from the SG-000065 tool contract.
//   npm run build -w @orcel/mcp && node scripts/generate-tool-contract-doc.mjs
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const contract = await import(pathToFileURL(join(repo, "apps", "orcel-mcp", "dist", "tool_contract.js")).href);
const { TOOL_CONTRACT, SURFACE_PROFILES, REMOTE_PROVIDER_PROFILES, BROWSER_FULL_CONTRACT } = contract;

const yes = (value) => (value ? "yes" : "no");
const names = Object.keys(TOOL_CONTRACT).sort();
const row = (name, e) => {
  const a = e.annotations;
  const remote = e.remote === "local_only" ? "local-only" : e.remote.join(" ");
  return `| \`${name}\` | \`${e.capability}/${e.operation}\` | ${e.effect} | ${e.approval} | ${remote} | ${yes(a.readOnlyHint)} | ${yes(a.destructiveHint)} | ${yes(a.idempotentHint)} | ${yes(a.openWorldHint)} | ${e.outputBound} |`;
};
const lines = [
  "# Orcel Tool Contract",
  "",
  "Status: CANONICAL CONTRACT FOR ORCEL-P16 (SG-000065). Generated by `scripts/generate-tool-contract-doc.mjs` from",
  "`apps/orcel-mcp/src/tool_contract.ts`; `apps/orcel-mcp/src/tool-contract.test.ts` pins the contract against the tool",
  "sources, MCP discovery on every transport, the OAuth scope matrix, the orceld remote-session scope table, the parity",
  "inventory, and this document.",
  "",
  "Discovery filtering is never authorization: orceld, the remote-session lease, and the OAuth ceilings enforce every call.",
  "",
  "## Profiles",
  "",
  "| Profile | Served by | Tools |",
  "| --- | --- | --- |",
  `| \`core\` | relay (remote) | ${SURFACE_PROFILES.core.length} |`,
  `| \`desktop_structured\` | stdio and loopback HTTP (local) | ${SURFACE_PROFILES.desktop_structured.length} |`,
  "",
  "The `developer` and `coordinate_fallback` profiles named in the plan are not mapped and deny. Unknown profiles deny.",
  "",
  "## Providers",
  "",
  "| Remote provider kind | Profile |",
  "| --- | --- |",
  ...Object.entries(REMOTE_PROVIDER_PROFILES).map(([provider, profile]) => `| \`${provider}\` | \`${profile}\` |`),
  "",
  "Every known remote provider shares the `core` ceiling; no provider gains or loses a tool relative to another. Local",
  "transports serve `desktop_structured` regardless of the configured provider kind, which is metadata and never proof of",
  "identity. A remote connection from any other provider kind is refused.",
  "",
  "## Tools",
  "",
  "Annotations: R = readOnlyHint, D = destructiveHint (may delete or overwrite existing user data), I = idempotentHint,",
  "O = openWorldHint (reaches network peers or runs a registered executable).",
  "",
  "| Tool | Kernel shape | Effect | Approval | Remote | R | D | I | O | Output bound |",
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ...names.map((name) => row(name, TOOL_CONTRACT[name])),
  "",
  "## browser_full (SG-000135, local only)",
  "",
  "Served by stdio and loopback HTTP only when local configuration selects it (`ORCEL_TOOL_SURFACE_PROFILE=browser_full`);",
  `never remote. It holds ${SURFACE_PROFILES.browser_full.length} tools: \`desktop_structured\` plus the Orcel Browser Session Broker tools below,`,
  "which orceld's broker maps onto the existing live host actions. Under this profile `browser_click`, `browser_fill`,",
  "`browser_select` and `browser_verify` are the broker tools listed here; `browser_structured` keeps its own forms.",
  "",
  "| Tool | Kernel shape | Effect | Approval | Remote | R | D | I | O | Output bound |",
  "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ...Object.keys(BROWSER_FULL_CONTRACT).map((name) => row(name, BROWSER_FULL_CONTRACT[name])),
  "",
  "SG-000135 OB-07: every broker session's pages go through orceld's takeover gate (`browser_structured` keeps it off).",
  "The gate can only refuse, before any approval prompt, and nothing is done when it does:",
  "",
  "- A page that shows a sign-in, one-time code, passkey or CAPTCHA check waits for the person (\"Needs you\"). Orcel never",
  "  solves, skips or fills one. Every action on that page, read or write, is refused with `HUMAN_VERIFICATION_REQUIRED`.",
  "  Successful page replies and `browser_task_status` list such pages under `needs_you` (page id, kind, closed signal",
  "  names, a fixed reason and the handoff), and the status also gives the active page's `page_state`. The page resumes",
  "  only after Orcel's own read-only check no longer sees the challenge and three quiet seconds have passed.",
  "- SG-000135 OB-06: in a Visible session, keyboard or mouse input while the session's own browser window is in front is",
  "  a person taking the browser over. Every action on the session's pages, read or write, is refused with `HUMAN_TAKEOVER`",
  "  until three seconds have passed with no such input (each input restarts the count); `page_state` is `HUMAN_OVERRIDE`",
  "  or `QUIET` meanwhile. Orcel reads only when the last input happened and which window is in front; it never injects",
  "  input. A Shadow session has no window, so no takeover.",
  "- After such a wait (or any other hold), a write before a new `browser_snapshot` is refused `TARGET_STALE`",
  "  (`reobserve_required`), and a write planned on an older observation is refused `TARGET_STALE` (`target_stale`).",
  "- A consequential write (an Enter that may submit, or a download; no tool of this profile sends one yet) whose outcome",
  "  is unknown is never admitted again, from this session or another session of the same MCP client, until it is",
  "  reconciled: `TARGET_STALE` (`outcome_uncertain`).",
  "",
  "See `docs/orcel/implementation-readiness/prep/OB07_CHALLENGE_HANDOFF.md`.",
  ""
];
writeFileSync(join(repo, "docs", "p16", "TOOL_CONTRACT.md"), lines.join("\n"));
console.log("wrote docs/p16/TOOL_CONTRACT.md");
